"""Generate ui/src/contracts.ts from the Aegis Pydantic models so the browser and the
engine share one contract. Run with no arguments to write the file; `--check` exits 1 when the
committed file is stale (tests/test_aegis_contracts.py enforces the same)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "app"
if str(APP) not in sys.path:
    sys.path.insert(0, str(APP))

OUTPUT = ROOT / "app/products/aegis/ui/src/contracts.ts"
HEADER = "// Generated by tools/aegis_contracts.py from the Aegis Pydantic models. Do not edit.\n"


def models():
    from products.aegis.backtest import BacktestRequest
    from products.aegis.optimize import OptimizeRequest
    from products.aegis.strategy import StrategySpec
    from products.aegis.walkforward import WalkForwardRequest

    return [StrategySpec, BacktestRequest, OptimizeRequest, WalkForwardRequest]


def _ts_type(schema: dict, defs: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(_ts_type(option, defs) for option in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(_literal(value) for value in schema["enum"])
    if "const" in schema:
        return _literal(schema["const"])
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "string":
        return "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(_ts_type(item, defs) for item in schema["prefixItems"]) + "]"
        items = schema.get("items")
        inner = _ts_type(items, defs) if isinstance(items, dict) else "unknown"
        return f"Array<{inner}>" if " | " in inner else f"{inner}[]"
    if kind == "object":
        if "properties" in schema:
            return "{ " + "; ".join(_fields(schema, defs)) + " }"
        values = schema.get("additionalProperties")
        if isinstance(values, dict):
            return f"Record<string, {_ts_type(values, defs)}>"
        return "Record<string, unknown>"
    return "unknown"


def _literal(value) -> str:
    if isinstance(value, str):
        return "'" + value.replace("'", "\\'") + "'"
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    return str(value)


def _fields(schema: dict, defs: dict) -> list[str]:
    required = set(schema.get("required", []))
    lines = []
    for name, prop in schema.get("properties", {}).items():
        optional = "" if name in required else "?"
        lines.append(f"{name}{optional}: {_ts_type(prop, defs)}")
    return lines


def _render_def(name: str, schema: dict, defs: dict) -> str:
    if "enum" in schema:
        return f"export type {name} = {_ts_type(schema, defs)};\n"
    body = "".join(f"  {line};\n" for line in _fields(schema, defs))
    return f"export interface {name} {{\n{body}}}\n"


INDICATOR_KIND_INTERFACE = """export interface IndicatorKind {
  outputs: string[];
  pane: 'price' | 'own';
  params: Record<string, number>;
  integer_params: string[];
  requires: string[];
  default_length: number;
  warmup_terms: string[];
  warmup_offset: number;
}
"""


def indicator_kinds() -> dict:
    """kinds.KINDS as plain JSON, emitted into contracts.ts as INDICATOR_KINDS (plan ruling P7)."""
    from products.aegis.kinds import KINDS

    return {
        name: {
            "outputs": list(info.outputs),
            "pane": info.pane,
            "params": dict(info.params),
            "integer_params": sorted(info.integer_params),
            "requires": list(info.requires),
            "default_length": info.default_length,
            "warmup_terms": list(info.warmup_terms),
            "warmup_offset": info.warmup_offset,
        }
        for name, info in KINDS.items()
    }


def render() -> str:
    defs: dict[str, dict] = {}
    roots: list[tuple[str, dict]] = []
    for model in models():
        schema = model.model_json_schema()
        for name, definition in schema.get("$defs", {}).items():
            defs.setdefault(name, definition)
        schema = {k: v for k, v in schema.items() if k != "$defs"}
        roots.append((model.__name__, schema))
    chunks = [HEADER, "\n"]
    for name in sorted(defs):
        chunks.append(_render_def(name, defs[name], defs))
        chunks.append("\n")
    for name, schema in roots:
        chunks.append(_render_def(name, schema, defs))
        chunks.append("\n")
    chunks.append(INDICATOR_KIND_INTERFACE)
    chunks.append("\n")
    chunks.append(
        "export const INDICATOR_KINDS: Record<string, IndicatorKind> = "
        + json.dumps(indicator_kinds(), indent=2)
        + ";\n"
    )
    return "".join(chunks).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
        if current != text:
            print(f"{OUTPUT} is stale; run tools/aegis_contracts.py", file=sys.stderr)
            return 1
        print("contracts.ts is current")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
